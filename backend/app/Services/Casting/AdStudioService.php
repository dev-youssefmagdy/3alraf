<?php

namespace App\Services\Casting;

use App\DTOs\Marketing\SocialMediaAssetData;
use App\Jobs\Casting\GenerateModelImageJob;
use App\Models\Marketer;
use App\Models\ModelGenerationHistory;
use App\Models\ModelPosePreset;
use App\Models\CastingLiveProduct;
use App\Models\Product;
use App\Models\VirtualModel;
use App\Services\Marketing\Media\SocialMediaLibraryService;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

/**
 * Ad workflow: product + approved model + concept / scene / outfit / background / camera / pose / format / provider → queued image (or video from an image).
 * Output is always a NEW private file; the product's own images and data are never modified. Results enter the private social-media library only on explicit action.
 */
class AdStudioService
{
    public const FORMATS = ['1:1', '4:5', '9:16', '16:9'];

    public function __construct(private ProviderManager $providers, private PromptBuilder $prompts, private SocialMediaLibraryService $library) {}

    /** Honest provider report shown in the UI: what it can and cannot guarantee. */
    public function capabilities(?string $provider = null): array
    {
        $p = $this->providers->make($provider);

        return ['provider' => $p->name()] + $p->capabilities();
    }

    public function createImage(VirtualModel $model, Product|CastingLiveProduct|Subject $product, array $v, Marketer $by): ModelGenerationHistory
    {
        if (! $model->isUsable()) {
            throw ValidationException::withMessages(['model' => __('casting.errors.model_not_approved')]);
        }
        $provider = in_array($v['provider'] ?? null, $this->providers->selectable(), true) ? $v['provider'] : config('casting.provider');
        $x = Subject::of($product);
        $params = $this->params($v);
        $caps = $this->providers->make($provider)->capabilities();
        $params['product_fidelity'] = ! empty($caps['reference_image']) ? 'reference_conditioned' : 'not_guaranteed';
        $params['identity_mode'] = $caps['identity'] ?? 'prompt_seed';
        $prompt = $this->prompts->ad($model, $x->name(), $x->description(), $params);

        // duplicate-job prevention: the same model + product + params already queued / running is returned instead of queued again
        $dupe = ModelGenerationHistory::query()->where('virtual_model_id', $model->id)->where('product_id', $x->productId())->where('live_product_id', $x->liveProductId())->where('kind', 'ad_image')
            ->whereIn('status', ['queued', 'running'])->where('prompt', $prompt)->first();
        if ($dupe) {
            return $dupe;
        }

        $h = ModelGenerationHistory::create(['virtual_model_id' => $model->id, 'product_id' => $x->productId(), 'live_product_id' => $x->liveProductId(), 'kind' => 'ad_image', 'provider' => $provider, 'status' => 'queued',
            'prompt' => $prompt, 'seed' => (int) $model->identity_seed, 'params' => $params, 'job_token' => $token = Str::random(32), 'created_by' => $by->id]);
        GenerateModelImageJob::dispatch($h->id, $token);

        return $h;
    }

    /** Image-to-video from a finished ad image (delegates to the Video Studio; refuses while video is unavailable / unverified). */
    public function createVideo(ModelGenerationHistory $image, Marketer $by, ?string $motion = null): ModelGenerationHistory
    {
        return app(VideoStudioService::class)->createFromGeneration($image, ['note' => $motion, 'provider' => $image->provider], $by);
    }

    /** Explicit hand-off of a finished generation into the private social library (review queue). */
    public function sendToLibrary(ModelGenerationHistory $h, Marketer $by): int
    {
        if ($h->status !== 'succeeded' || ! $h->output_path || $h->social_media_asset_id || ! $h->product_id) {   // live-product results go through LivePushService
            throw ValidationException::withMessages(['generation' => __('casting.errors.not_ready')]);
        }
        $bytes = (string) CastingStorage::disk()->get($h->output_path);
        $tmp = tempnam(sys_get_temp_dir(), 'cast');
        file_put_contents($tmp, $bytes);
        $file = new UploadedFile($tmp, 'casting-'.$h->id.'.'.pathinfo($h->output_path, PATHINFO_EXTENSION), null, null, true);
        $data = SocialMediaAssetData::fromArray(['kind' => str_starts_with((string) (new \finfo(FILEINFO_MIME_TYPE))->buffer($bytes), 'video') ? 'video' : 'image',
            'title' => Str::limit(($h->virtualModel?->name ?? 'AI model').' — '.$h->product?->name, 190, ''), 'tags' => 'ai-casting',
            'brief' => 'Generated by the AI Casting Studio. Real product fidelity is not guaranteed by the generator: compare against the product photo before use.',
            'generation_meta' => ['origin' => 'ai_casting', 'generation_id' => $h->id, 'virtual_model_id' => $h->virtual_model_id, 'provider' => $h->provider, 'seed' => $h->seed, 'product_fidelity' => $h->params['product_fidelity'] ?? null]]);
        try {
            $asset = $this->library->create($h->product, $data, $file, $by);
        } finally {
            @unlink($tmp);
        }
        $h->update(['social_media_asset_id' => $asset->id]);

        return $asset->id;
    }

    private function params(array $v): array
    {
        $txt = fn ($k, $n = 200) => isset($v[$k]) && trim((string) $v[$k]) !== '' ? Str::limit(trim(strip_tags((string) $v[$k])), $n, '') : null;
        $pose = ModelPosePreset::query()->where('type', 'pose')->where('is_active', true)->where('key', $v['pose'] ?? '')->value('key');
        $cam = ModelPosePreset::query()->where('type', 'camera')->where('is_active', true)->where('key', $v['camera'] ?? '')->value('key');

        return array_filter(['concept' => $txt('concept', 300), 'scene' => $txt('scene'), 'outfit' => $txt('outfit'), 'background' => $txt('background'), 'campaign' => $txt('campaign', 120),
            'pose' => $pose, 'camera' => $cam, 'format' => in_array($v['format'] ?? null, self::FORMATS, true) ? $v['format'] : '4:5'], fn ($x) => $x !== null);
    }
}
